//   await initEngine()                    // once; browsers fetch pkg/swarm_wasm_bg.wasm
//   const game = GameHandle.newGame(Date.now())
//   game.apply({ do: 'buy_unit', unit: 'drone', amount: { num: '1' } })
//   game.advance(100)
