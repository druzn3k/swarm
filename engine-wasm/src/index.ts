/** The wasm-bindgen class (pkg/swarm_wasm.d.ts), restated so this package
 * type-checks before pkg/ is built. */
interface WasmGame {
  free(): void
  load_report(): string
  static_view(): string
  view(request_json: string): string
  apply(command_json: string): string
  advance_ms(dt_ms: number): void
  resync_wall(wall_now_ms: number): string | undefined
  mark_closed(wall_now_ms: number): void
  export_v2(wall_now_ms: number): string
  export_legacy?(wall_now_ms: number): string
  parse_number(input: string, unit_name?: string | null): string | undefined
  ui_state(): string
  welcome_back(force: boolean): string | undefined
  unit_stats(unit_name: string): string
}

interface WasmModule {
  default(input?: { module_or_path: unknown }): Promise<unknown>
  Game: {
    new_game(wall_now_ms: number): WasmGame
    load(save_text: string, wall_now_ms: number, heartbeat_ms?: number | null): WasmGame
  }
  format_short(num: string): string
  format_long(num: string): string
  detect_save_format(text: string): string | undefined
  convert_save(text: string, to: string): string
}

/** What initEngine accepts: a URL to fetch, the bytes, or a compiled module.
 * Default: pkg/swarm_wasm_bg.wasm next to the JS glue (Vite rewrites the
 * URL). In Node, which can't fetch file: URLs, pass the bytes. */
export type WasmSource = string | URL | Response | BufferSource | WebAssembly.Module

let wasm: WasmModule | undefined
let initPromise: Promise<void> | undefined

async function importGlue(): Promise<WasmModule> {
  // @ts-ignore pkg/ is generated by `pnpm build`; WasmModule types it
  return (await import('../pkg/swarm_wasm.js')) as WasmModule
}

/** Loads and instantiates the wasm module once; later calls share it. */
export function initEngine(source?: WasmSource): Promise<void> {
  initPromise ??= (async () => {
    const mod = await importGlue()
    await mod.default(source === undefined ? undefined : { module_or_path: source })
    wasm = mod
  })().catch((e) => {
    initPromise = undefined
    throw e
  })
  return initPromise
}

/** Whether initEngine has finished. */
export function isEngineReady(): boolean {
  return wasm !== undefined
}

function engine(): WasmModule {
  if (!wasm) throw new Error('@swarmsim/engine-wasm: call `await initEngine()` first')
  return wasm
}

/** A running game. Call `free()` when done with it (or let it be collected). */
export class GameHandle {
  private game: WasmGame
  private statics: StaticView | undefined

  private constructor(game: WasmGame) {
    this.game = game
  }

  /** A new game at `wallNowMs` (epoch ms). */
  static newGame(wallNowMs: number = Date.now()): GameHandle {
    return new GameHandle(engine().Game.new_game(wallNowMs))
  }

  /**
   * Loads a v1 (`swarmhive-v1` localStorage) or v2 save. `heartbeatMs`: the
   * last time the game was seen running, if later than the save's dates.
   * Throws if the text is not a loadable save.
   */
  static load(saveText: string, wallNowMs: number = Date.now(), heartbeatMs?: number): GameHandle {
    return new GameHandle(engine().Game.load(saveText, wallNowMs, heartbeatMs ?? null))
  }

  /** The save format, warnings and offline report of `load` (format `"new"` for `newGame`). */
  loadReport(): LoadReport {
    return JSON.parse(this.game.load_report()) as LoadReport
  }

  /** Names, texts, costs, tabs: never changes, cached after the first call. */
  staticView(): StaticView {
    this.statics ??= JSON.parse(this.game.static_view()) as StaticView
    return this.statics
  }

  /** The per-tick view. Drains the queued events into `events`. */
  view(request: ViewRequest = {}): View {
    return JSON.parse(this.game.view(JSON.stringify(request))) as View
  }

  /** Runs a command; throws the engine's message on failure. */
  apply(command: Command): CommandOutcome {
    return JSON.parse(this.game.apply(JSON.stringify(command))) as CommandOutcome
  }

  /** Moves the clock forward by a monotonic delta (ms; sub-ms parts carry over). */
  advance(dtMs: number): void {
    this.game.advance_ms(dtMs)
  }

  /** After a suspend or hidden tab: adds the wall-clock gap if it exceeds 5 s. */
  resyncWall(wallNowMs: number = Date.now()): OfflineReport | null {
    const r = this.game.resync_wall(wallNowMs)
    return r === undefined ? null : (JSON.parse(r) as OfflineReport)
  }

  /** Records that the game was closed (heartbeat, `pagehide`). */
  markClosed(wallNowMs: number = Date.now()): void {
    this.game.mark_closed(wallNowMs)
  }

  /** The game as a v2 save (`SW2|...`). */
  exportV2(wallNowMs: number = Date.now()): string {
    return this.game.export_v2(wallNowMs)
  }

  /** The game as a v1 save the TS/Coffee game imports (needs the `legacy-write` feature, on by default). */
  exportLegacy(wallNowMs: number = Date.now()): string {
    if (!this.game.export_legacy) throw new Error('built without the legacy-write feature')
    return this.game.export_legacy(wallNowMs)
  }

  /** Player number input (`"1.5k"`, `"50%"`, `"=10"`, `"@100"`); null if unparseable. The `%`/`=`/`@` forms need a unit name. */
  parseNumber(input: string, unitName?: string): NumString | null {
    return this.game.parse_number(input, unitName ?? null) ?? null
  }

  /** The UI's part of the save: the options bag (`set_option` writes it) and the save's unknown top-level keys. */
  uiState(): UiState {
    return JSON.parse(this.game.ui_state()) as UiState
  }

  /**
   * A welcome-back report computed now for the time since the loaded save
   * was closed; `force`: even after a short absence. Not stored in the
   * game (unlike `view().welcome_back`, which `load` computes once).
   */
  welcomeBack(force = false): WelcomeBack | null {
    const r = this.game.welcome_back(force)
    return r === undefined ? null : (JSON.parse(r) as WelcomeBack)
  }

  /**
   * A unit's stats and production, visible or not (the view's `detail` has
   * them for visible focused units only). Throws for unknown names.
   */
  unitStats(unitName: string): UnitStats {
    return JSON.parse(this.game.unit_stats(unitName)) as UnitStats
  }

  /** Releases the wasm memory. The handle is unusable afterwards. */
  free(): void {
    this.game.free()
  }
}

/** `await initEngine()`, then `GameHandle.newGame`. */
export async function newGame(wallNowMs: number = Date.now()): Promise<GameHandle> {
  await initEngine()
  return GameHandle.newGame(wallNowMs)
}

/** `await initEngine()`, then `GameHandle.load`. */
export async function loadGame(
  saveText: string,
  wallNowMs: number = Date.now(),
  heartbeatMs?: number,
): Promise<GameHandle> {
  await initEngine()
  return GameHandle.load(saveText, wallNowMs, heartbeatMs)
}

/** The app's short number format: `"99,999"`, `"100K"`, `"1.23M"`, `"1.5e400"`. */
export function formatShort(num: NumString): string {
  return engine().format_short(num)
}

/** The app's long number format: `"123.456 thousand"`, `"1.23456 million"`. */
export function formatLong(num: NumString): string {
  return engine().format_long(num)
}

/** `"v1"`, `"v2"`, or null if `text` is not a save. */
export function detectSaveFormat(text: string): SaveFormat | null {
  return (engine().detect_save_format(text) as SaveFormat | undefined) ?? null
}

/** Re-encodes a save (state unchanged: no backfill, no new dates). */
export function convertSave(text: string, to: SaveFormat): string {
  return engine().convert_save(text, to)
}
