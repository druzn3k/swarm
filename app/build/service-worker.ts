// Vite plugin: writes dist/sw.js, a service worker that makes the installed
// app work offline. It precaches every file of this build (hashed names, so
// each build gets a fresh cache), serves the page network-first so a deploy
// shows up on the next launch, and keeps the Google Fonts for offline use.
//
// The page: the network gets NETWORK_TIMEOUT_MILLIS to answer, then the
// cached app shell is shown (a stalled connection must not leave the
// installed app blank); a late answer still refreshes the cache. Only a good
// (res.ok) answer for the app's own page ("./" or "./index.html", any query)
// is cached as the shell, so a 404 or 5xx elsewhere under the scope can't
// replace it. Precaching and page fetches bypass the browser's HTTP cache
// (GitHub Pages sends max-age=600): an old index.html in a new cache would
// point at hashed assets that activating that cache deletes.
import type { Plugin } from "vite";
import { readdirSync, statSync } from "node:fs";
import { join, relative } from "node:path";
import { createHash } from "node:crypto";

function publicFiles(dir: string, root = dir): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? publicFiles(path, root) : [relative(root, path).split("\\").join("/")];
  });
}

export function serviceWorker(): Plugin {
  let publicDir = "";
  return {
    name: "swarmhive-service-worker",
    apply: "build",
    configResolved(config) {
      publicDir = config.publicDir;
    },
    generateBundle(_options, bundle) {
      const files = [...Object.keys(bundle), ...publicFiles(publicDir)].filter((f) => !f.endsWith(".map")).sort();
      const version = createHash("sha256").update(files.join("\n")).digest("hex").slice(0, 12);
      this.emitFile({ type: "asset", fileName: "sw.js", source: swSource(version, ["./", ...files.map((f) => "./" + f)]) });
    },
  };
}

/** how long a page request waits for the network before the cached app shell is shown */
export const NETWORK_TIMEOUT_MILLIS = 2500;

function swSource(version: string, assets: string[]): string {
  return `// Generated by build/service-worker.ts. Do not edit.
const CACHE = "swarmhive-${version}";
const FONTS = "swarmhive-fonts";
const ASSETS = ${JSON.stringify(assets)};
const NETWORK_TIMEOUT = ${NETWORK_TIMEOUT_MILLIS};
// the app's own page: the directory sw.js is in, or its index.html
const SHELL_PATHS = [new URL("./", self.location.href).pathname, new URL("./index.html", self.location.href).pathname];

self.addEventListener("install", (event) => {
  // cache: "reload" skips the HTTP cache, so this build's files are what we store
  event.waitUntil(
    caches.open(CACHE)
      .then((c) => c.addAll(ASSETS.map((url) => new Request(url, { cache: "reload" }))))
      .then(() => self.skipWaiting())
  );
});

function cachedShell() {
  return caches.match("./", { cacheName: CACHE, ignoreVary: true }).then((r) => r || caches.match("./index.html", { ignoreVary: true }));
}

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("swarmhive-") && k !== CACHE && k !== FONTS).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin === self.location.origin) {
    // the page: network first, so a new deploy loads; the cached shell
    // offline or when the network is slow to answer
    if (req.mode === "navigate") {
      const isShell = url.origin === self.location.origin && SHELL_PATHS.includes(url.pathname);
      let stored = Promise.resolve();
      // no-cache: revalidate with the server rather than trust the HTTP cache
      const network = fetch(new Request(req, { cache: "no-cache" })).then((res) => {
        // only a good copy of the app's own page replaces the cached shell
        if (res.ok && isShell) {
          const copy = res.clone();
          stored = caches.open(CACHE).then((c) => c.put("./", copy));
        }
        return res;
      });
      // keep the worker alive until a late answer is stored
      event.waitUntil(network.then(() => stored, () => undefined));
      event.respondWith(
        new Promise((resolve) => {
          let answered = false;
          network.then(
            (res) => {
              answered = true;
              resolve(res);
            },
            () => {
              answered = true;
              resolve(cachedShell().then((r) => r || Response.error()));
            }
          );
          setTimeout(() => {
            if (answered) return;
            // the network is stalling: show the cached shell, if there is one
            cachedShell().then((r) => {
              if (r && !answered) {
                answered = true;
                resolve(r);
              }
            });
          }, NETWORK_TIMEOUT);
        })
      );
      return;
    }
    // hashed assets and icons: cache first
    // ignoreVary: a server's "Vary: Origin" must not hide the precached copy from module requests
    event.respondWith(caches.match(req, { ignoreSearch: true, ignoreVary: true }).then((hit) => hit || fetch(req)));
    return;
  }
  // Google Fonts: serve the cached copy, refresh it in the background
  if (url.hostname === "fonts.googleapis.com" || url.hostname === "fonts.gstatic.com") {
    event.respondWith(
      caches.open(FONTS).then((c) =>
        c.match(req).then((hit) => {
          const fresh = fetch(req).then((res) => {
            c.put(req, res.clone());
            return res;
          });
          return hit || fresh;
        })
      )
    );
  }
});
`;
}
