// Writes ./static.ts: the decoded spreadsheet (toSpreadsheet()), in the
// compact form of ./compact.ts, so the engine doesn't run the io-ts codecs at
// every launch. Run `pnpm --filter @swarmsim/tables gen:static` after editing
// the tables; static.test.ts fails until you do.
import fs from "fs";
import path from "path";
import toSpreadsheet from "./data";
import { compact } from "./compact";

export function staticSource(): string {
  const json = JSON.stringify(compact(toSpreadsheet() as any));
  return `// Generated by src/spreadsheet/gen-static.ts from toSpreadsheet(). Do not edit:
// edit the tables, then run \`pnpm --filter @swarmsim/tables gen:static\`.
import type { CompactSpreadsheet } from "./compact";

// JSON.parse of a string is quicker to load than the same object literal
const data: CompactSpreadsheet = JSON.parse(${JSON.stringify(json)});
export default data;
`;
}

if (require.main === module) {
  fs.writeFileSync(path.join(__dirname, "static.ts"), staticSource());
}
